CREATE TABLE app_users (
    id VARCHAR(36) PRIMARY KEY,
    email VARCHAR(254) NOT NULL UNIQUE,
    display_name VARCHAR(80) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL
);
CREATE TABLE auth_sessions (
    token_hash CHAR(64) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL REFERENCES app_users(id),
    expires_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_sessions_expiry ON auth_sessions(expires_at);
CREATE TABLE workspaces (
    id VARCHAR(36) PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    created_by VARCHAR(36) NOT NULL REFERENCES app_users(id),
    created_at TIMESTAMP NOT NULL
);
CREATE TABLE workspace_members (
    workspace_id VARCHAR(36) NOT NULL REFERENCES workspaces(id),
    user_id VARCHAR(36) NOT NULL REFERENCES app_users(id),
    role VARCHAR(16) NOT NULL CHECK (role IN ('OWNER', 'MEMBER')),
    PRIMARY KEY (workspace_id, user_id)
);
CREATE TABLE documents (
    id VARCHAR(36) PRIMARY KEY,
    workspace_id VARCHAR(36) NOT NULL REFERENCES workspaces(id),
    owner_id VARCHAR(36) NOT NULL REFERENCES app_users(id),
    visibility VARCHAR(16) NOT NULL CHECK (visibility IN ('PRIVATE', 'GROUP')),
    title VARCHAR(240) NOT NULL,
    filename VARCHAR(255) NOT NULL,
    media_type VARCHAR(80) NOT NULL,
    content_hash CHAR(64) NOT NULL,
    source_bytes BLOB NOT NULL,
    status VARCHAR(16) NOT NULL,
    error_message VARCHAR(500),
    page_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    UNIQUE (workspace_id, owner_id, visibility, content_hash)
);
CREATE TABLE document_chunks (
    id VARCHAR(36) PRIMARY KEY,
    document_id VARCHAR(36) NOT NULL REFERENCES documents(id),
    page_number INT NOT NULL,
    chunk_index INT NOT NULL,
    content CLOB NOT NULL,
    UNIQUE (document_id, chunk_index)
);
CREATE TABLE reading_notes (
    id VARCHAR(36) PRIMARY KEY,
    document_id VARCHAR(36) NOT NULL REFERENCES documents(id),
    user_id VARCHAR(36) NOT NULL REFERENCES app_users(id),
    visibility VARCHAR(16) NOT NULL CHECK (visibility IN ('PRIVATE', 'GROUP')),
    reading_status VARCHAR(16) NOT NULL CHECK (reading_status IN ('READING', 'DONE', 'BLOCKED')),
    content CLOB NOT NULL,
    version INT NOT NULL DEFAULT 1,
    updated_at TIMESTAMP NOT NULL,
    UNIQUE (document_id, user_id)
);
CREATE TABLE meetings (
    id VARCHAR(36) PRIMARY KEY,
    workspace_id VARCHAR(36) NOT NULL REFERENCES workspaces(id),
    created_by VARCHAR(36) NOT NULL REFERENCES app_users(id),
    title VARCHAR(240) NOT NULL,
    meeting_date DATE NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    draft_json CLOB,
    minutes CLOB NOT NULL DEFAULT '',
    minutes_version INT NOT NULL DEFAULT 0,
    proposals_json CLOB,
    proposals_version INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL
);
CREATE TABLE jobs (
    id VARCHAR(36) PRIMARY KEY,
    workspace_id VARCHAR(36) NOT NULL REFERENCES workspaces(id),
    requested_by VARCHAR(36) NOT NULL REFERENCES app_users(id),
    kind VARCHAR(32) NOT NULL CHECK (kind IN ('IMPORT', 'MEETING_DRAFT', 'MINUTE_ACTIONS')),
    resource_id VARCHAR(36) NOT NULL,
    request_key VARCHAR(100) NOT NULL,
    request_hash CHAR(64) NOT NULL,
    payload_json CLOB NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('QUEUED', 'RUNNING', 'SUCCEEDED', 'FAILED', 'CANCELLED')),
    attempts INT NOT NULL DEFAULT 0,
    available_at TIMESTAMP NOT NULL,
    lease_until TIMESTAMP,
    lease_token VARCHAR(36),
    result_json CLOB,
    error_message VARCHAR(500),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    UNIQUE (workspace_id, requested_by, kind, request_key)
);
CREATE INDEX idx_jobs_claim ON jobs(status, available_at, lease_until);
CREATE TABLE job_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id VARCHAR(36) NOT NULL REFERENCES jobs(id),
    phase VARCHAR(40) NOT NULL,
    message VARCHAR(500) NOT NULL,
    created_at TIMESTAMP NOT NULL
);
CREATE TABLE action_tasks (
    id VARCHAR(36) PRIMARY KEY,
    workspace_id VARCHAR(36) NOT NULL REFERENCES workspaces(id),
    meeting_id VARCHAR(36) NOT NULL REFERENCES meetings(id),
    created_by VARCHAR(36) NOT NULL REFERENCES app_users(id),
    assignee_id VARCHAR(36) REFERENCES app_users(id),
    title VARCHAR(300) NOT NULL,
    due_date DATE,
    status VARCHAR(20) NOT NULL CHECK (status IN ('TODO', 'IN_PROGRESS', 'DONE', 'CANCELLED')),
    proposal_version INT NOT NULL,
    proposal_index INT NOT NULL,
    confirmation_hash CHAR(64) NOT NULL,
    version INT NOT NULL DEFAULT 1,
    created_at TIMESTAMP NOT NULL,
    UNIQUE (meeting_id, proposal_version, proposal_index)
);
CREATE TABLE efficiency_measurements (
    id VARCHAR(36) PRIMARY KEY,
    workspace_id VARCHAR(36) NOT NULL REFERENCES workspaces(id),
    user_id VARCHAR(36) NOT NULL REFERENCES app_users(id),
    scenario VARCHAR(40) NOT NULL,
    baseline_ms BIGINT NOT NULL CHECK (baseline_ms > 0),
    assisted_ms BIGINT NOT NULL CHECK (assisted_ms >= 0),
    review_ms BIGINT NOT NULL CHECK (review_ms >= 0),
    quality_accepted BOOLEAN NOT NULL,
    notes VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP NOT NULL
);
